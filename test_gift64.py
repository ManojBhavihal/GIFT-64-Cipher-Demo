"""
Test suite for GIFT-64-128 cipher implementation.
==================================================

Test vectors are taken DIRECTLY from the official GIFT repository:
    https://github.com/giftcipher/gift
    File: implementations/test vectors/GIFT64_test_vector_{1,2,3}.txt

These test vectors were generated by the official C++ reference code
written by Siang Meng Sim (one of the GIFT authors).
"""

import pytest
import sys
import os

# Add parent directory to path so we can import gift64
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gift64 import (
    encrypt, decrypt, encrypt_verbose,
    sub_cells, sub_cells_inv,
    perm_bits, perm_bits_inv,
    SBOX, SBOX_INV, PERM, PERM_INV,
    _int_to_nibbles, _nibbles_to_int,
)


# ──────────────────────────────────────────────────────────────────────
# OFFICIAL TEST VECTORS
# ──────────────────────────────────────────────────────────────────────
# Source: github.com/giftcipher/gift → implementations/test vectors/
#
# The C++ code stores state as nibbles printed MSB-first:
#   "f6 2b c3 ef 34 f7 75 ac" means nibbles [c,a,5,7,7,f,4,3,f,e,3,c,b,2,6,f]
#   which is the integer 0xf62bc3ef34f775ac
#
# IMPORTANT: The hex display in the test vector files shows two nibbles
# per byte as [high_nibble][low_nibble], read from MSB to LSB.
# ──────────────────────────────────────────────────────────────────────

# Test Vector 1: All-zeros
TV1_PLAINTEXT  = 0x0000000000000000
TV1_KEY        = 0x00000000000000000000000000000000
TV1_CIPHERTEXT = 0xf62bc3ef34f775ac

# Test Vector 2: Counting pattern
TV2_PLAINTEXT  = 0xfedcba9876543210
TV2_KEY        = 0xfedcba9876543210fedcba9876543210
TV2_CIPHERTEXT = 0xc1b71f66160ff587

# Test Vector 3: Random values
TV3_PLAINTEXT  = 0xc450c7727a9b8a7d
TV3_KEY        = 0xbd91731eb6bc2713a1f9f6ffc75044e7
TV3_CIPHERTEXT = 0xe3272885fa94ba8b


# ──────────────────────────────────────────────────────────────────────
# ENCRYPTION TESTS (against official test vectors)
# ──────────────────────────────────────────────────────────────────────

class TestEncryption:
    """Test encryption against all three official test vectors."""

    def test_encrypt_tv1_all_zeros(self):
        """Official TV1: all-zero plaintext and key."""
        result = encrypt(TV1_PLAINTEXT, TV1_KEY)
        assert result == TV1_CIPHERTEXT, (
            f"TV1 FAILED: expected 0x{TV1_CIPHERTEXT:016x}, got 0x{result:016x}"
        )

    def test_encrypt_tv2_counting(self):
        """Official TV2: counting pattern plaintext and key."""
        result = encrypt(TV2_PLAINTEXT, TV2_KEY)
        assert result == TV2_CIPHERTEXT, (
            f"TV2 FAILED: expected 0x{TV2_CIPHERTEXT:016x}, got 0x{result:016x}"
        )

    def test_encrypt_tv3_random(self):
        """Official TV3: random plaintext and key."""
        result = encrypt(TV3_PLAINTEXT, TV3_KEY)
        assert result == TV3_CIPHERTEXT, (
            f"TV3 FAILED: expected 0x{TV3_CIPHERTEXT:016x}, got 0x{result:016x}"
        )


# ──────────────────────────────────────────────────────────────────────
# DECRYPTION TESTS (round-trip AND direct verification)
# ──────────────────────────────────────────────────────────────────────

class TestDecryption:
    """Test decryption: both round-trip and direct ciphertext→plaintext."""

    def test_decrypt_tv1(self):
        """Decrypt the official TV1 ciphertext back to all-zeros."""
        result = decrypt(TV1_CIPHERTEXT, TV1_KEY)
        assert result == TV1_PLAINTEXT, (
            f"TV1 decrypt FAILED: expected 0x{TV1_PLAINTEXT:016x}, got 0x{result:016x}"
        )

    def test_decrypt_tv2(self):
        """Decrypt the official TV2 ciphertext back to counting pattern."""
        result = decrypt(TV2_CIPHERTEXT, TV2_KEY)
        assert result == TV2_PLAINTEXT, (
            f"TV2 decrypt FAILED: expected 0x{TV2_PLAINTEXT:016x}, got 0x{result:016x}"
        )

    def test_decrypt_tv3(self):
        """Decrypt the official TV3 ciphertext back to random plaintext."""
        result = decrypt(TV3_CIPHERTEXT, TV3_KEY)
        assert result == TV3_PLAINTEXT, (
            f"TV3 decrypt FAILED: expected 0x{TV3_PLAINTEXT:016x}, got 0x{result:016x}"
        )

    def test_roundtrip_tv1(self):
        """Encrypt then decrypt TV1 → should recover original plaintext."""
        ct = encrypt(TV1_PLAINTEXT, TV1_KEY)
        pt = decrypt(ct, TV1_KEY)
        assert pt == TV1_PLAINTEXT

    def test_roundtrip_tv2(self):
        """Encrypt then decrypt TV2 → should recover original plaintext."""
        ct = encrypt(TV2_PLAINTEXT, TV2_KEY)
        pt = decrypt(ct, TV2_KEY)
        assert pt == TV2_PLAINTEXT

    def test_roundtrip_tv3(self):
        """Encrypt then decrypt TV3 → should recover original plaintext."""
        ct = encrypt(TV3_PLAINTEXT, TV3_KEY)
        pt = decrypt(ct, TV3_KEY)
        assert pt == TV3_PLAINTEXT

    def test_roundtrip_arbitrary(self):
        """Round-trip test with a non-official value."""
        pt = 0x123456789ABCDEF0
        key = 0xDEADBEEFCAFEBABE0123456789ABCDEF
        ct = encrypt(pt, key)
        recovered = decrypt(ct, key)
        assert recovered == pt, (
            f"Round-trip failed: expected 0x{pt:016x}, got 0x{recovered:016x}"
        )


# ──────────────────────────────────────────────────────────────────────
# ROUND-BY-ROUND VERIFICATION (against official trace from TV1)
# ──────────────────────────────────────────────────────────────────────

class TestRoundTrace:
    """Verify intermediate states match the official test vector trace.

    These values come from GIFT64_test_vector_1.txt.
    The C++ code prints state as MSB-first hex bytes.
    """

    def test_round0_subcells_tv1(self):
        """After SubCells in round 0 of TV1, state should be 0x1111111111111111.

        All-zero nibbles → S[0]=1 for all 16 nibbles.
        """
        result = encrypt_verbose(TV1_PLAINTEXT, TV1_KEY)
        r0 = result['rounds'][0]
        assert r0['after_subcells'] == '1111111111111111', (
            f"Round 0 SubCells mismatch: got {r0['after_subcells']}"
        )


# ──────────────────────────────────────────────────────────────────────
# COMPONENT-LEVEL TESTS (S-box and permutation correctness)
# ──────────────────────────────────────────────────────────────────────

class TestComponents:
    """Verify that individual components are correct and invertible."""

    def test_sbox_is_bijection(self):
        """The S-box must be a bijection (each output appears exactly once)."""
        assert sorted(SBOX) == list(range(16)), "S-box is not a bijection!"

    def test_sbox_inv_is_correct(self):
        """SBOX_INV[SBOX[x]] must equal x for all x."""
        for x in range(16):
            assert SBOX_INV[SBOX[x]] == x, f"Inverse S-box fails at x={x}"
            assert SBOX[SBOX_INV[x]] == x, f"S-box of inverse fails at x={x}"

    def test_perm_is_bijection(self):
        """The permutation table must be a permutation of 0..63."""
        assert sorted(PERM) == list(range(64)), "PERM is not a permutation!"

    def test_perm_inv_is_correct(self):
        """PERM_INV[PERM[i]] must equal i for all i."""
        for i in range(64):
            assert PERM_INV[PERM[i]] == i, f"Inverse perm fails at i={i}"
            assert PERM[PERM_INV[i]] == i, f"Perm of inverse fails at i={i}"

    def test_subcells_invertibility(self):
        """SubCells followed by inverse SubCells should be identity."""
        state = list(range(16))  # [0, 1, 2, ..., 15]
        result = sub_cells_inv(sub_cells(state))
        assert result == state

    def test_permbits_invertibility(self):
        """PermBits followed by inverse PermBits should be identity."""
        state = [i % 16 for i in range(16)]
        result = perm_bits_inv(perm_bits(state))
        assert result == state

    def test_nibble_int_roundtrip(self):
        """Converting int → nibbles → int should be identity."""
        for val in [0, 1, 0xDEADBEEF, 0xFFFFFFFFFFFFFFFF]:
            nibs = _int_to_nibbles(val, 16)
            assert _nibbles_to_int(nibs) == val


# ──────────────────────────────────────────────────────────────────────
# INPUT VALIDATION TESTS
# ──────────────────────────────────────────────────────────────────────

class TestInputValidation:
    """Verify that invalid inputs are rejected."""

    def test_encrypt_negative_plaintext(self):
        with pytest.raises(ValueError):
            encrypt(-1, 0)

    def test_encrypt_oversized_plaintext(self):
        with pytest.raises(ValueError):
            encrypt(1 << 64, 0)

    def test_encrypt_negative_key(self):
        with pytest.raises(ValueError):
            encrypt(0, -1)

    def test_encrypt_oversized_key(self):
        with pytest.raises(ValueError):
            encrypt(0, 1 << 128)

    def test_decrypt_negative_ciphertext(self):
        with pytest.raises(ValueError):
            decrypt(-1, 0)


