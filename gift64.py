"""
GIFT-64-128 Lightweight Block Cipher — Pure Python Implementation
=================================================================

Implements the GIFT-64 block cipher as specified in:
    "GIFT: A Small Present"
    Banik, Pandey, Peyrin, Sim, Todo, Sasaki — CHES 2017

Parameters:
    - Block size:  64 bits  (8 bytes)
    - Key size:   128 bits (16 bytes)
    - Rounds:      28

This implementation is written for CLARITY and EDUCATIONAL use.
It is NOT intended for production security applications.

Reference: Official C++ code from https://github.com/giftcipher/gift
           by Siang Meng Sim (one of the GIFT authors).
"""

# ──────────────────────────────────────────────────────────────────────
# CONSTANTS  (copied verbatim from the official GIFT-64-128_cipher.cpp)
# ──────────────────────────────────────────────────────────────────────

# 4-bit S-box: maps each nibble (0–15) to another nibble
SBOX = [1, 10, 4, 12, 6, 15, 3, 9, 2, 13, 11, 7, 5, 0, 8, 14]

# Inverse S-box: used during decryption
# Built so that SBOX_INV[SBOX[x]] == x for all x in 0..15
SBOX_INV = [13, 0, 8, 6, 2, 12, 4, 11, 14, 7, 1, 10, 3, 9, 15, 5]

# Bit permutation table: bit at position i moves to position PERM[i]
# (64 entries, one per bit of the 64-bit block)
PERM = [
     0, 17, 34, 51, 48,  1, 18, 35, 32, 49,  2, 19, 16, 33, 50,  3,
     4, 21, 38, 55, 52,  5, 22, 39, 36, 53,  6, 23, 20, 37, 54,  7,
     8, 25, 42, 59, 56,  9, 26, 43, 40, 57, 10, 27, 24, 41, 58, 11,
    12, 29, 46, 63, 60, 13, 30, 47, 44, 61, 14, 31, 28, 45, 62, 15,
]

# Inverse bit permutation: PERM_INV[PERM[i]] == i for all i
PERM_INV = [
     0,  5, 10, 15, 16, 21, 26, 31, 32, 37, 42, 47, 48, 53, 58, 63,
    12,  1,  6, 11, 28, 17, 22, 27, 44, 33, 38, 43, 60, 49, 54, 59,
     8, 13,  2,  7, 24, 29, 18, 23, 40, 45, 34, 39, 56, 61, 50, 55,
     4,  9, 14,  3, 20, 25, 30, 19, 36, 41, 46, 35, 52, 57, 62, 51,
]

# Round constants (6-bit values generated by an LFSR, pre-computed for 62 rounds)
# GIFT-64 uses only the first 28 of these.
ROUND_CONSTANTS = [
    0x01, 0x03, 0x07, 0x0F, 0x1F, 0x3E, 0x3D, 0x3B, 0x37, 0x2F,
    0x1E, 0x3C, 0x39, 0x33, 0x27, 0x0E, 0x1D, 0x3A, 0x35, 0x2B,
    0x16, 0x2C, 0x18, 0x30, 0x21, 0x02, 0x05, 0x0B, 0x17, 0x2E,
    0x1C, 0x38, 0x31, 0x23, 0x06, 0x0D, 0x1B, 0x36, 0x2D, 0x1A,
    0x34, 0x29, 0x12, 0x24, 0x08, 0x11, 0x22, 0x04, 0x09, 0x13,
    0x26, 0x0C, 0x19, 0x32, 0x25, 0x0A, 0x15, 0x2A, 0x14, 0x28,
    0x10, 0x20,
]

NUM_ROUNDS = 28


# ──────────────────────────────────────────────────────────────────────
# INTERNAL REPRESENTATION
# ──────────────────────────────────────────────────────────────────────
#
# The official C++ code stores the 64-bit state as an array of 16 nibbles:
#     state = [n0, n1, n2, ..., n15]    (each nibble is 0–15)
#     where n0 holds the LEAST significant 4 bits, n15 the MOST significant.
#
# Similarly, the 128-bit key is stored as 32 nibbles:
#     key = [k0, k1, k2, ..., k31]
#     where k0 is least significant, k31 most significant.
#
# We work with Python integers externally (more natural) and convert
# to/from nibble arrays internally.
# ──────────────────────────────────────────────────────────────────────


def _int_to_nibbles(value: int, count: int) -> list[int]:
    """Convert an integer to a list of `count` nibbles (LSB first).

    Example:
        _int_to_nibbles(0xABCD, 4) → [0xD, 0xC, 0xB, 0xA]
    """
    nibbles = []
    for _ in range(count):
        nibbles.append(value & 0xF)
        value >>= 4
    return nibbles


def _nibbles_to_int(nibbles: list[int]) -> int:
    """Convert a list of nibbles (LSB first) back to an integer.

    Example:
        _nibbles_to_int([0xD, 0xC, 0xB, 0xA]) → 0xABCD
    """
    result = 0
    for i in range(len(nibbles) - 1, -1, -1):
        result = (result << 4) | nibbles[i]
    return result


def _nibbles_to_bits(nibbles: list[int]) -> list[int]:
    """Expand nibbles into individual bits (LSB of nibble 0 = bit 0)."""
    bits = []
    for nib in nibbles:
        for j in range(4):
            bits.append((nib >> j) & 1)
    return bits


def _bits_to_nibbles(bits: list[int]) -> list[int]:
    """Pack individual bits back into nibbles."""
    count = len(bits) // 4
    nibbles = []
    for i in range(count):
        nib = 0
        for j in range(4):
            nib |= bits[4 * i + j] << j
        nibbles.append(nib)
    return nibbles


# ──────────────────────────────────────────────────────────────────────
# ROUND OPERATIONS (match the C++ code line-by-line)
# ──────────────────────────────────────────────────────────────────────


def sub_cells(state: list[int]) -> list[int]:
    """Apply the 4-bit S-box to each of the 16 nibbles (SubCells step).

    This is the ONLY non-linear operation in the cipher. It provides
    *confusion*: a small change in one nibble produces a different nibble.
    """
    return [SBOX[nib] for nib in state]


def sub_cells_inv(state: list[int]) -> list[int]:
    """Inverse SubCells: apply the inverse S-box for decryption."""
    return [SBOX_INV[nib] for nib in state]


def perm_bits(state: list[int]) -> list[int]:
    """Rearrange all 64 bits according to the permutation table (PermBits step).

    This provides *diffusion*: bits from one nibble get spread across
    many different nibbles, so the effect of SubCells propagates widely.
    """
    bits = _nibbles_to_bits(state)
    perm = [0] * 64
    for i in range(64):
        perm[PERM[i]] = bits[i]
    return _bits_to_nibbles(perm)


def perm_bits_inv(state: list[int]) -> list[int]:
    """Inverse PermBits: reverse the bit permutation for decryption."""
    bits = _nibbles_to_bits(state)
    perm = [0] * 64
    for i in range(64):
        perm[PERM_INV[i]] = bits[i]
    return _bits_to_nibbles(perm)


def add_round_key(state: list[int], key: list[int], round_num: int) -> list[int]:
    """XOR round key bits and round constant into the state (AddRoundKey step).

    From the 128-bit key register (32 nibbles), the first 16 key-nibble-bits
    are XORed into bit positions 4*i (i=0..15), and the next 16 key-nibble-bits
    into bit positions 4*i+1.

    A 6-bit round constant is also XORed into specific bit positions,
    plus a constant '1' into bit 63.
    """
    # Convert state and key to individual bits
    bits = _nibbles_to_bits(state)
    key_bits = _nibbles_to_bits(key)

    # XOR key bits into the state
    # key_bits[0..15] → state bit positions 0, 4, 8, ..., 60  (every 4th bit)
    # key_bits[16..31] → state bit positions 1, 5, 9, ..., 61 (every 4th bit + 1)
    kbc = 0  # key bit counter
    for i in range(16):
        bits[4 * i] ^= key_bits[kbc]
        bits[4 * i + 1] ^= key_bits[kbc + 16]
        kbc += 1

    # XOR round constant (6 bits) into specific positions
    rc = ROUND_CONSTANTS[round_num]
    bits[3] ^= rc & 1
    bits[7] ^= (rc >> 1) & 1
    bits[11] ^= (rc >> 2) & 1
    bits[15] ^= (rc >> 3) & 1
    bits[19] ^= (rc >> 4) & 1
    bits[23] ^= (rc >> 5) & 1

    # XOR constant '1' into bit 63
    bits[63] ^= 1

    return _bits_to_nibbles(bits)


def key_update(key: list[int]) -> list[int]:
    """Update the 128-bit key register for the next round.

    The key schedule has three parts:
    1. Rotate the entire 128-bit key right by 32 bits.
    2. Apply a 12-bit rotation to the top 16-bit word (k0).
    3. Apply a 2-bit rotation to the second 16-bit word (k1).
    """
    temp = [0] * 32

    # Step 1: Rotate entire key right by 32 bits
    # (In nibble terms, shift by 8 nibbles)
    for i in range(32):
        temp[i] = key[(i + 8) % 32]

    new_key = [0] * 32
    # Copy the lower 24 nibbles directly
    for i in range(24):
        new_key[i] = temp[i]

    # Step 2: k0 (nibbles 24–27) rotated right by 12 bits
    # In the C++ code: key[24]=temp[27], key[25]=temp[24], etc.
    new_key[24] = temp[27]
    new_key[25] = temp[24]
    new_key[26] = temp[25]
    new_key[27] = temp[26]

    # Step 3: k1 (nibbles 28–31) rotated right by 2 bits
    # This operates on individual bits within the nibbles
    new_key[28] = ((temp[28] & 0xC) >> 2) ^ ((temp[29] & 0x3) << 2)
    new_key[29] = ((temp[29] & 0xC) >> 2) ^ ((temp[30] & 0x3) << 2)
    new_key[30] = ((temp[30] & 0xC) >> 2) ^ ((temp[31] & 0x3) << 2)
    new_key[31] = ((temp[31] & 0xC) >> 2) ^ ((temp[28] & 0x3) << 2)

    return new_key


def key_update_inv(key: list[int]) -> list[int]:
    """Reverse the key update (used to recover previous round keys for decryption).

    This undoes key_update() so that if key_update(k) == k', then
    key_update_inv(k') == k.
    """
    temp = [0] * 32

    # Undo step 3: inverse of 2-bit rotation on k1 (nibbles 28–31)
    # Original: new[28] = ((old[28]&0xC)>>2) ^ ((old[29]&0x3)<<2)
    # We need to recover the 'old' (pre-step-3) nibbles from the current ones.
    # The inverse of a 2-bit right rotation on 16 bits is a 2-bit left rotation.
    temp[28] = ((key[28] & 0x3) << 2) ^ ((key[31] & 0xC) >> 2)
    temp[29] = ((key[29] & 0x3) << 2) ^ ((key[28] & 0xC) >> 2)
    temp[30] = ((key[30] & 0x3) << 2) ^ ((key[29] & 0xC) >> 2)
    temp[31] = ((key[31] & 0x3) << 2) ^ ((key[30] & 0xC) >> 2)

    # Undo step 2: inverse of 12-bit rotation on k0 (nibbles 24–27)
    # Original: new[24]=old[27], new[25]=old[24], new[26]=old[25], new[27]=old[26]
    # So: old[24]=new[25], old[25]=new[26], old[26]=new[27], old[27]=new[24]
    temp[24] = key[25]
    temp[25] = key[26]
    temp[26] = key[27]
    temp[27] = key[24]

    # Copy lower 24 nibbles
    for i in range(24):
        temp[i] = key[i]

    # Undo step 1: inverse of 32-bit right rotation = 32-bit left rotation
    # Original: temp[i] = key[(i+8)%32]
    # Inverse: new_key[(i+8)%32] = temp[i]  →  new_key[j] = temp[(j-8)%32]
    new_key = [0] * 32
    for i in range(32):
        new_key[i] = temp[(i - 8) % 32]

    return new_key


# ──────────────────────────────────────────────────────────────────────
# PUBLIC API
# ──────────────────────────────────────────────────────────────────────


def encrypt(plaintext: int, key: int) -> int:
    """Encrypt a 64-bit plaintext with a 128-bit key using GIFT-64.

    Args:
        plaintext: An integer in range [0, 2^64 - 1].
        key:       An integer in range [0, 2^128 - 1].

    Returns:
        The 64-bit ciphertext as an integer.
    """
    if not (0 <= plaintext < (1 << 64)):
        raise ValueError(f"Plaintext must be a 64-bit integer (0 to 2^64-1), got {plaintext}")
    if not (0 <= key < (1 << 128)):
        raise ValueError(f"Key must be a 128-bit integer (0 to 2^128-1), got {key}")

    state = _int_to_nibbles(plaintext, 16)
    k = _int_to_nibbles(key, 32)

    for r in range(NUM_ROUNDS):
        state = sub_cells(state)       # 1. Substitution (confusion)
        state = perm_bits(state)       # 2. Permutation  (diffusion)
        state = add_round_key(state, k, r)  # 3. Key mixing
        k = key_update(k)             # 4. Advance key register

    return _nibbles_to_int(state)


def decrypt(ciphertext: int, key: int) -> int:
    """Decrypt a 64-bit ciphertext with a 128-bit key using GIFT-64.

    Args:
        ciphertext: An integer in range [0, 2^64 - 1].
        key:        An integer in range [0, 2^128 - 1].

    Returns:
        The 64-bit plaintext as an integer.
    """
    if not (0 <= ciphertext < (1 << 64)):
        raise ValueError(f"Ciphertext must be a 64-bit integer (0 to 2^64-1), got {ciphertext}")
    if not (0 <= key < (1 << 128)):
        raise ValueError(f"Key must be a 128-bit integer (0 to 2^128-1), got {key}")

    state = _int_to_nibbles(ciphertext, 16)
    k = _int_to_nibbles(key, 32)

    # Pre-compute all round key states (same as the C++ decryption code)
    round_key_states = []
    for r in range(NUM_ROUNDS):
        round_key_states.append(list(k))  # Save a copy of the key state
        k = key_update(k)

    # Decrypt in reverse round order
    for r in range(NUM_ROUNDS - 1, -1, -1):
        state = add_round_key(state, round_key_states[r], r)  # Inverse AddRoundKey (XOR is its own inverse)
        state = perm_bits_inv(state)   # Inverse permutation
        state = sub_cells_inv(state)   # Inverse substitution

    return _nibbles_to_int(state)


def encrypt_verbose(plaintext: int, key: int) -> dict:
    """Encrypt with full round-by-round details (for educational display).

    Returns a dict with:
        - 'ciphertext': the final ciphertext integer
        - 'rounds': list of dicts, one per round, each containing the
                     state after SubCells, PermBits, AddRoundKey, and
                     the updated key (all as hex strings).
    """
    state = _int_to_nibbles(plaintext, 16)
    k = _int_to_nibbles(key, 32)

    rounds = []
    for r in range(NUM_ROUNDS):
        round_info = {'round': r}

        state = sub_cells(state)
        round_info['after_subcells'] = format(_nibbles_to_int(state), '016x')

        state = perm_bits(state)
        round_info['after_permbits'] = format(_nibbles_to_int(state), '016x')

        state = add_round_key(state, k, r)
        round_info['after_addroundkey'] = format(_nibbles_to_int(state), '016x')

        k = key_update(k)
        round_info['updated_key'] = format(_nibbles_to_int(k), '032x')

        rounds.append(round_info)

    return {
        'ciphertext': _nibbles_to_int(state),
        'rounds': rounds,
    }
